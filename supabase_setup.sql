CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

CREATE TABLE IF NOT EXISTS public.assessments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    age integer,
    pain_level integer,
    pain_type text,
    pain_duration text,
    cold_sensitivity text,
    hot_sensitivity text,
    chewing_pain text,
    gum_bleeding text,
    gum_swelling text,
    bad_breath text,
    tooth_mobility text,
    recent_dental_treatment text,
    affected_teeth text,
    description text,
    image_filename text,
    image_mime_type text,
    ai_analysis text,
    concern_level text
);

CREATE TABLE IF NOT EXISTS public.knowledge_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    source text,
    content text NOT NULL,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    embedding extensions.vector(768) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS knowledge_documents_embedding_idx
    ON public.knowledge_documents
    USING hnsw (embedding extensions.vector_cosine_ops);

CREATE OR REPLACE FUNCTION public.match_documents(
    query_embedding extensions.vector(768),
    match_threshold double precision,
    match_count integer
)
RETURNS TABLE (
    id bigint,
    title text,
    source text,
    content text,
    similarity double precision
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        document.id,
        document.title,
        document.source,
        document.content,
        1 - (document.embedding <=> query_embedding) AS similarity
    FROM public.knowledge_documents AS document
    WHERE 1 - (document.embedding <=> query_embedding) > match_threshold
    ORDER BY document.embedding <=> query_embedding
    LIMIT GREATEST(match_count, 0);
$$;

ALTER TABLE public.assessments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.knowledge_documents ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT, INSERT ON public.assessments TO service_role;
GRANT SELECT, INSERT ON public.knowledge_documents TO service_role;
GRANT USAGE, SELECT ON SEQUENCE
    public.assessments_id_seq,
    public.knowledge_documents_id_seq
TO service_role;
GRANT EXECUTE ON FUNCTION public.match_documents(
    extensions.vector,
    double precision,
    integer
) TO service_role;
